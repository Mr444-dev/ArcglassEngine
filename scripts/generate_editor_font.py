"""Generate the editor's compact HLSL bitmap font from the bundled Inter font.

Requires Pillow only when regenerating the source include; normal engine builds
use the committed EditorFont.hlsli and do not need Python or Pillow.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


CELL_WIDTH = 12
CELL_HEIGHT = 14
FONT_SIZE = 12
SUPERSAMPLE = 4


def render_glyph(font: ImageFont.FreeTypeFont, character: str) -> list[int]:
    image = Image.new("L", (CELL_WIDTH * SUPERSAMPLE, CELL_HEIGHT * SUPERSAMPLE), 0)
    draw = ImageDraw.Draw(image)
    bounds = draw.textbbox((0, 0), character, font=font)
    glyph_width = draw.textlength(character, font=font)
    ascent, descent = font.getmetrics()
    baseline = (image.height - ascent - descent) * 0.5 + ascent
    x = max(0.0, (font.getlength(character) - glyph_width) * 0.5) - bounds[0]
    y = baseline - ascent
    draw.text((x, y), character, fill=255, font=font)

    resampling = getattr(Image, "Resampling", Image).LANCZOS
    image = image.resize((CELL_WIDTH, CELL_HEIGHT), resampling)
    pixels = image.load()
    return [pixels[column, row] for row in range(CELL_HEIGHT) for column in range(CELL_WIDTH)]


def generate(font_path: Path, output_path: Path) -> None:
    font = ImageFont.truetype(str(font_path), FONT_SIZE * SUPERSAMPLE)
    words: list[int] = []
    advances: list[int] = []
    for codepoint in range(32, 128):
        character = chr(codepoint)
        coverage = render_glyph(font, character)
        advance_quarters = round(font.getlength(character) / SUPERSAMPLE * 4.0)
        advances.append(max(0, min(255, advance_quarters)))
        for group in range((CELL_WIDTH * CELL_HEIGHT) // 8):
            word = 0
            for pixel_index in range(8):
                coverage4 = min(15, (coverage[group * 8 + pixel_index] + 8) // 17)
                word |= coverage4 << (pixel_index * 4)
            words.append(word)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    advance_words: list[int] = []
    for start in range(0, len(advances), 4):
        word = 0
        for index, advance in enumerate(advances[start : start + 4]):
            word |= advance << (index * 8)
        advance_words.append(word)

    lines = [
        "// Generated by scripts/generate_editor_font.py from the bundled Inter font.",
        f"// {CELL_WIDTH}x{CELL_HEIGHT} glyph cells, {FONT_SIZE}px Inter metrics, and 4-bit antialias coverage.",
        f"static const uint FontGlyphs[{96 * (CELL_WIDTH * CELL_HEIGHT // 8)}] = {{",
    ]
    for start in range(0, len(words), 8):
        group = words[start : start + 8]
        lines.append("    " + ", ".join(f"0x{word:08X}u" for word in group) + ",")
    lines.append("};")
    lines.append(f"static const uint FontAdvances[{len(advance_words)}] = {{")
    for start in range(0, len(advance_words), 8):
        group = advance_words[start : start + 8]
        lines.append("    " + ", ".join(f"0x{word:08X}u" for word in group) + ",")
    lines.append("};")
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("third_party/fonts/Inter/Inter.ttf"))
    parser.add_argument("--output", type=Path, default=Path("shaders/editor/EditorFont.hlsli"))
    args = parser.parse_args()
    generate(args.font, args.output)


if __name__ == "__main__":
    main()
